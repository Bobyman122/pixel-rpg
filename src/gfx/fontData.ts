// Hand-drawn variable-width bitmap font. Rows are separated by "/".
// Row 0 is the top of capitals; the baseline sits under row 6, rows 7-8 are descenders.
// `g(rows, top)` prepends `top` blank rows so lowercase letters and punctuation line up.

function g(rows: string, top = 0): string[] {
  const list = rows.split('/');
  const width = list[0].length;
  return [...Array(top).fill('.'.repeat(width)), ...list];
}

